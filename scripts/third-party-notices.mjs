// Writes THIRD_PARTY_NOTICES.md from the licence files of all production dependencies.
import { execSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dirs = execSync('npm ls --omit=dev --all --parseable', { encoding: 'utf8' }).trim().split('\n').slice(1)
const seen = new Map()
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const key = `${pkg.name}@${pkg.version}`
  if (seen.has(key)) continue
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f))
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  const url = (repo || pkg.homepage || '')
    .replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '')
    .replace(/^([\w-]+\/[\w.-]+)$/, 'https://github.com/$1')
  const license = pkg.license === 'SEE LICENSE IN LICENSE' ? 'MIT with bpmn.io watermark clause' : pkg.license
  seen.set(key, { name: pkg.name, version: pkg.version, license, url, text: file ? readFileSync(join(dir, file), 'utf8').trim() : '' })
}
const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

let out = `# Third-party notices

Process Simulator (the web app and the Camunda Modeler plugin) includes the following open source packages. Each is used under the licence shown; the full licence texts follow below.

This file is generated by \`npm run notices\`.

| Package | Version | Licence | Source |
| --- | --- | --- | --- |
`
for (const p of list) out += `| ${p.name} | ${p.version} | ${p.license} | ${p.url} |\n`
for (const p of list) out += `\n## ${p.name} ${p.version}\n\n${p.url}\n\n\`\`\`text\n${p.text || `Licence: ${p.license}`}\n\`\`\`\n`
writeFileSync('THIRD_PARTY_NOTICES.md', out)
console.log(`${list.length} packages`)
